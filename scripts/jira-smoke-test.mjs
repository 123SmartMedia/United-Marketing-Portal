#!/usr/bin/env node
/**
 * Explicitly-invoked Jira smoke test.
 * -----------------------------------
 *   npm run jira:smoke -- --confirm
 *
 * Creates ONE clearly labelled test request in the configured Jira service desk,
 * using the same auth config and the same field mapping as the production route,
 * then prints the ticket key so it can be closed or deleted.
 *
 * It refuses to run without `--confirm`, and it is never part of `npm test` —
 * automated tests mock Jira and create nothing.
 *
 * Attachments are not exercised here (they need an object staged in R2); verify
 * those with a real submission on a preview deployment.
 */

import { randomUUID } from 'node:crypto';

import {
  loadEnvFile,
  resolveScriptConfig,
  describeConfig,
  apiFetch,
  explainStatus,
  fail,
} from './lib/jira-script-auth.mjs';

loadEnvFile();

const { buildRequestFieldValues } = await import('../src/lib/jira/fieldMap.js');

if (!process.argv.includes('--confirm')) {
  fail(
    'This creates a REAL Jira ticket in the configured service desk.\n' +
      'Re-run with --confirm when you are ready:\n\n  npm run jira:smoke -- --confirm'
  );
}

const { config, authorization } = resolveScriptConfig({
  extraRequired: [
    ['JIRA_SERVICE_DESK_ID', process.env.JIRA_SERVICE_DESK_ID],
    ['JIRA_REQUEST_TYPE_ID', process.env.JIRA_REQUEST_TYPE_ID],
  ],
});

const correlationId = randomUUID();
const stamp = new Date().toISOString();

const submission = {
  name: 'Integration Smoke Test',
  email: config.serviceAccountEmail || 'marketing@unitedmortgage.com',
  phone: '631-203-7480',
  nmls: '0000000',
  branch: 'Automated test — not a real request',
  requestType: 'Custom / Other',
  dateNeeded: new Date(Date.now() + 14 * 86400000).toISOString().slice(0, 10),
  rush: false,
  projectTitle: `[TEST — PLEASE CLOSE] Jira integration smoke test ${stamp}`,
  keyMessage:
    'Automated smoke test from marketing.unitedmortgage.com. No action needed — close or delete this ticket.',
  additionalDetails: `Generated by npm run jira:smoke at ${stamp}.`,
  files: [],
};

const { requestFieldValues, mapped, unmapped } = buildRequestFieldValues(submission, {
  correlationId,
  submittedFrom: 'jira-smoke-test',
});

console.log(describeConfig(config));
console.log(`Service desk  : ${config.serviceDeskId}`);
console.log(`Request type  : ${config.requestTypeId}`);
console.log(`Mapped fields : ${mapped.length ? mapped.map((m) => `${m.key}->${m.fieldId}`).join(', ') : '(none)'}`);
console.log(`In description: ${unmapped.join(', ') || '(none)'}`);
console.log('\nCreating test request…\n');

let created;
try {
  created = await apiFetch('/rest/servicedeskapi/request', {
    authorization,
    config,
    method: 'POST',
    body: {
      serviceDeskId: config.serviceDeskId,
      requestTypeId: config.requestTypeId,
      requestFieldValues,
    },
  });
} catch (err) {
  console.error(`FAILED — ${err.message}`);
  console.error(explainStatus(err.status, config));
  if (err.body) console.error(`\nJira said:\n${err.body}`);
  if (err.status === 400 || err.status === 422) {
    console.error(
      '\n400/422 usually means a required field is missing or an option value is wrong — ' +
        're-run `npm run jira:discover` and compare the required fields.'
    );
  }
  process.exit(1);
}

console.log('SUCCESS');
console.log(`  Ticket : ${created.issueKey}`);
console.log(`  Portal : ${created._links?.web || '(none returned)'}`);
console.log('\nClose or delete this ticket in Jira when you are done.');
